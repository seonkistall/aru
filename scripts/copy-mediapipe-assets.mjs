import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

// The MediaPipe JS API is bundled into the build; the WASM runtime it drives is copied
// here and served from /public. Those two halves are only compatible because they come
// from the same package version, and nothing in either half checks: the bundle looks up
// `self.ModuleFactory` and then calls Emscripten exports (`_changeBinaryGraph`,
// `_addIntToInputStream`, ...) straight off the module. So the copy goes into a
// directory named after the installed version and `app/scan/mediapipe-version.ts` — the
// module the URL in `app/scan/landmarker-config.ts` is built from — is written in the
// same pass. Both halves of the URL therefore come from this one read of the package,
// and a version bump changes the URL, which is what makes a warm service-worker or HTTP
// cache miss instead of pairing the new bundle with the runtime it already holds.

const pkg = resolve("node_modules/@mediapipe/tasks-vision/package.json");
if (!existsSync(pkg)) throw new Error("Install @mediapipe/tasks-vision before copying assets.");
const version = JSON.parse(readFileSync(pkg, "utf8")).version;
// The version becomes a URL path segment, a directory name and a string literal in
// generated TypeScript. Refuse anything that is not plainly all three.
if (typeof version !== "string" || !/^[0-9A-Za-z][0-9A-Za-z.+-]*$/.test(version)) {
  throw new Error(`Unusable @mediapipe/tasks-vision version: ${JSON.stringify(version)}`);
}

const source = resolve("node_modules/@mediapipe/tasks-vision/wasm");
if (!existsSync(source)) throw new Error("Install @mediapipe/tasks-vision before copying assets.");
const vendor = resolve("public/vendor/mediapipe");
const target = resolve(vendor, version, "wasm");
mkdirSync(target, { recursive: true });
cpSync(source, target, { recursive: true });

// One version at a time in /public, or every upgrade would leave another ~34 MB behind
// in the repository. Only directories are considered, which is what keeps the
// unversioned `face_landmarker.task` and `NOTICE.md` — neither of them shipped by the
// package — out of it. The legacy unversioned `wasm/` directory is removed by the same
// rule. (`public/sw.js` prunes the equivalent stale entries out of a visitor's cache.)
const stale = readdirSync(vendor, { withFileTypes: true })
  .filter((entry) => entry.isDirectory() && entry.name !== version)
  .map((entry) => entry.name);
for (const name of stale) rmSync(resolve(vendor, name), { recursive: true, force: true });

const generated = resolve("app/scan/mediapipe-version.ts");
const contents = `// Generated by scripts/copy-mediapipe-assets.mjs (npm postinstall). Do not edit.
// The installed @mediapipe/tasks-vision version, which is also the directory the same
// script copied the runtime into under public/vendor/mediapipe/.
export const MEDIAPIPE_VERSION = ${JSON.stringify(version)};
`;
// Written only when it would change, so a repeat install leaves the working tree clean.
const changed = !existsSync(generated) || readFileSync(generated, "utf8") !== contents;
if (changed) writeFileSync(generated, contents);

console.log(
  `MediaPipe WASM assets copied to public/vendor/mediapipe/${version}/wasm` +
    `${stale.length ? ` (removed ${stale.join(", ")})` : ""}${changed ? "; version module rewritten" : ""}.`,
);
